import { readdir, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const projectRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const audioRoot = path.join(projectRoot, "raydjsetmp3s");
const outputPath = path.join(projectRoot, "src/data/localMusicAlbums.js");
const publicBaseUrl = "https://audio.inanimate.space";

const albumTitleOverrides = {
  "elie b - 2023 album": "Elie B — 2023 Album",
  "prospect paradigm": "Prospect Paradigm",
  "ray - 2023 EP": "2023 EP",
  "ray - AMOEBA [raw]「2020-2021」⟨sliced⟩":
    "AMOEBA [raw]「2020–2021」⟨sliced⟩",
  "ray - Ego Death 2025": "Ego Death",
  "ray - Return. 2026": "Return.",
  "ray - unreleased singles": "Unreleased Singles",
  "ray 2016-2018": "2016–2018",
  "ray singles (released)": "Released Singles",
  "skulpt - the album": "SKULPT",
  "skulpt - the album (remixes)": "SKULPT — Remixes",
  "twolittlestrawberries - album 0": "Two Little Strawberries — Album 0",
};

const encodeObjectPath = (segments) =>
  segments.map((segment) => encodeURIComponent(segment)).join("/");

const directories = (await readdir(audioRoot, { withFileTypes: true }))
  .filter((entry) => entry.isDirectory())
  .sort((first, second) => first.name.localeCompare(second.name));

const albums = await Promise.all(
  directories.map(async (directory, index) => {
    const tracks = (await readdir(path.join(audioRoot, directory.name), {
      withFileTypes: true,
    }))
      .filter((entry) => entry.isFile() && /\.mp3$/i.test(entry.name))
      .sort((first, second) =>
        first.name.localeCompare(second.name, undefined, {
          numeric: true,
          sensitivity: "base",
        })
      )
      .map((entry) => ({
        type: "audio",
        title: entry.name.replace(/\.mp3$/i, ""),
        src: `${publicBaseUrl}/${encodeObjectPath([
          directory.name,
          entry.name,
        ])}`,
      }));

    return {
      id: `local-album-${directory.name
        .toLowerCase()
        .replace(/[^a-z0-9]+/g, "-")}`,
      title: albumTitleOverrides[directory.name] || directory.name,
      coverStyle: "local-album",
      coverHue: (index * 31 + 188) % 360,
      description: `${tracks.length} streamed ${
        tracks.length === 1 ? "track" : "tracks"
      }.`,
      media: tracks,
      links: [],
    };
  })
);

const output = `// Generated by scripts/generate-audio-manifest.mjs\n// Audio streams from ${publicBaseUrl}; MP3 files are not bundled with the site.\nexport const localMusicAlbums = ${JSON.stringify(albums, null, 2)};\n`;

await writeFile(outputPath, output);
console.log(`Generated ${albums.length} albums with ${albums.reduce((total, album) => total + album.media.length, 0)} tracks.`);
